import os
# GPU끼리 데이터를 직접 주고받는 P2P(Peer-to-Peer) 기능을 끕니다. 
# 일부 서버 환경에서 하드웨어 호환성 문제로 학습이 멈추는 것을 방지합니다.
os.environ['NCCL_P2P_DISABLE'] = '1'
# InfiniBand(초고속 네트워크) 기능을 끕니다. 
# 로컬 서버 내 GPU 통신 시 발생할 수 있는 네트워크 병목과 에러를 막아줍니다.
os.environ['NCCL_IB_DISABLE'] = '1'
# YOLOv11을 실행하기 위한 최신 엔진을 불러옵니다.
from ultralytics import YOLO

# 학습할 준비를 합니다.
model = YOLO('yolo11m.pt')
# 데이터셋의 정보(클래스 수, 이미지 경로 등)가 적힌 설정 파일의 위치를 지정합니다.
yaml_path = "/home/pfcheon/Desktop/limdoyeon/carplate.v1i.yolov11/data.yaml"


# 멀티 GPU 학습 시 프로세스가 복제되는데, 이때 학습 시작 명령이 중복 실행되지 않도록 보호하는 구문
# https://docs.ultralytics.com/ko/guides/yolo-data-augmentation/#scale-scale
if __name__ == '__main__':
    model.train(
        # 이전 학습이 중단된 지점(Epoch)부터 자동으로 이어서 시작합니다.
        data=yaml_path,
        # 전체 학습 횟수를 300회로 설정합니다.
        epochs=500,
        # 검증 손실이 80번의 에포크 동안 개선되지 않으면 시간을 아끼기 위해 학습을 조기 종료합니다.
        patience=100,
        # 입력 이미지 해상도를 640x640으로 설정합니다.
        imgsz=640,
        # 4개의 GPU가 한 번의 연산 단계에서 처리할 총 이미지 개수입니다. (각 GPU당 8장씩 분배됨)
        batch=32,
        # 정밀도 연산을 16비트와 32비트를 섞어 사용하여 학습 속도를 높이고 GPU 메모리를 아낍니다.
        amp=True,
        # CPU가 이미지를 전처리하여 GPU로 전달하는 통로(Thread)의 개수입니다.
        workers=16,
        # 서버에 장착된 0번부터 3번까지의 GPU 4개를 모두 사용하여 학습 속도를 4배로 높입니다.
        device=[0, 1, 2, 3],
        
        # 데이터 증강 (Augmentation) 및 하이퍼파라미터

        # 이미지를 최대 ±40도 범위 내에서 무작위로 회전
        degrees=60.0,
        # 이미지를 가로/세로 방향으로 전체 크기의 25%만큼 이동
        translate=0.50,
        # 이미지를 75% 범위 내에서 확대하거나 축소합니다.
        scale=0.3,
        # 이미지를 최대 18도 각도로 비틉니다(평행사변형처럼). 카메라 렌즈의 왜곡이나 비스듬한 시야각을 학습합니다.
        shear=18.0,
        # 이미지에 원근감을 줍니다. 가까운 쪽은 크게, 먼 쪽은 작게 보이게 하여 차량이 대각선 방향으로 진입할 때의 왜곡을 흉내 냅니다.
        perspective=0.0009,
        # 상하 반전 이미지를 위아래로 뒤집을 확률이 40%입니다. (※주의: 숫자 인식에서는 '6'이 '9'로 보일 수 있어 보통 0으로 설정)
        # flipud=0,
        # 이미지를 좌우로 뒤집을 확률이 50%입니다.
        # fliplr=0.5,


        # 4장의 이미지를 무작위로 잘라 한 장의 이미지로 합치는 기법을 90% 확률로 사용합니다
        # https://leedakyeong.tistory.com/entry/Python-Object-Detection-Mosaic-Augmentation-YOLO-v5
        mosaic=0.9,
        # 두 장의 이미지를 서로 투명하게 겹쳐서 새로운 데이터를 만듭니다. 모델이 배경 노이즈에 덜 민감해지도록 돕습니다.
        # mixup=0.25,
        # 한 이미지의 객체(번호판)를 복사해서 다른 이미지의 배경에 무작위로 붙여넣습니다. 객체 주위의 배경이 바뀌어도 객체를 잘 인식하게 합니다.
        # copy_paste=0.35,
        # 학습 중에 입력 이미지 크기를 매번 바꾸는 기능을 끕니다. 서버의 GPU 메모리가 부족할 때 에러를 방지하기 위한 안정적인 설정입니다.
        multi_scale=True, 
        # : 이미지의 색상(H), 채도(S), 명도(V)를 무작위로 바꿉니다. 햇빛이 강한 낮, 조명이 어두운 밤, 비 오는 날 등 다양한 조명 조건에 대비합니다.
        hsv_h=0.04,
        hsv_s=0.8,
        hsv_v=0.5,
        # 가중치 감쇠(Weight Decay)를 개선한 Adam 최적화 도구입니다. 복잡한 글자 형태를 빠르게 학습하면서도 안정적인 성능을 냅니다.
        optimizer='AdamW',
        # 학습을 시작할 때의 초기 학습률입니다. 너무 크면 학습이 튀고, 너무 작으면 속도가 느립니다.
        lr0=0.0008,
        # 최종 학습률이 초기 학습률의 어느 정도 수준(0.8%)까지 줄어들지를 결정합니다.
        lrf=0.008,
        # 가중치가 너무 커지지 않게 규제하여 모델이 특정 데이터에만 과하게 적응하는 '과적합'을 방지합니다.
        weight_decay=0.001,
        # 기울기(Gradient) 계산 시 이전의 방향성을 얼마나 유지할지 결정하는 관성 값입니다.
        momentum=0.937,
        # 학습 종료 15에포크 전에는 mosaic 증강을 끕니다. 마지막에는 실제와 똑같은 깨끗한 이미지를 보면서 모델이 세밀한 오차를 교정하게 합니다.
        close_mosaic=15,
        # 학습률을 코사인 함수 그래프 모양으로 부드럽게 줄여나갑니다. 학습 후반부에 정밀한 튜닝이 가능해집니다.
        cos_lr=True,
        # 학습 시 무작위로 신경망의 15%를 사용하지 않습니다. 모델이 특정 뉴런에만 의존하지 않고 전체적으로 튼튼해지도록(일반화) 합니다.
        dropout=0.15,
        # 정답 데이터에 대해 100% 확신하는 대신 10% 정도의 여지를 둡니다. 이는 모델이 가짜 정답이나 노이즈 섞인 데이터에 대해 너무 예민하게 반응하지 않도록 유연하게 만들어줍니다.
        label_smoothing=0,
        name='EV_Plate_Character_MultiClass_v9'
    )
